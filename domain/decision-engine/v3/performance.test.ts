import { expect, it } from 'vitest';
import { generateCandidatePolicies } from '../candidates';
import { evaluateConstraints } from '../constraints';
import { evaluateScenario, replayDecisionV3 } from '../engine';
import { taiwanMarket } from '../markets/taiwan';
import { evaluateCandidate, markParetoOptimal } from '../monteCarlo';
import { deriveAdaptiveWeights } from '../objective';
import { generateDisturbances } from '../random';
import { decisionScenarios } from '../scenarios';
import { createCommerceDigitalTwin } from '../state';
import { analyzeDecisionBoundary } from './counterfactual';
import { simulateForecastEnsemble } from './forecast';
import { DEFAULT_ACTIVE_POLICY } from './policyRegistry';
import { evaluateRobustRisk, rankRobustRisks } from './risk';
import { fuseWorldState } from './worldModel';

it('benchmarks fusion, 100/500/1000 trajectories, counterfactual boundary and replay',()=>{
  const scenario=decisionScenarios.traffic;
  const twin=createCommerceDigitalTwin(taiwanMarket,scenario.events,scenario.seed);
  const state=twin.currentState as typeof twin.initialState;
  const candidates=generateCandidatePolicies(state,taiwanMarket);
  const weights=deriveAdaptiveWeights(state,taiwanMarket);
  const disturbances=generateDisturbances(scenario.seed,32);
  const evaluations=markParetoOptimal(candidates.map(candidate=>evaluateCandidate(candidate,evaluateConstraints(candidate,state,taiwanMarket),state,taiwanMarket,weights,disturbances)));
  const measured=<T,>(run:()=>T)=>{const started=performance.now();const value=run();return {value,ms:Number((performance.now()-started).toFixed(2))}};
  const fusion=measured(()=>fuseWorldState(state));
  const runs=([100,500,1000] as const).map(count=>({count,...measured(()=>simulateForecastEnsemble(evaluations,state,taiwanMarket,weights,DEFAULT_ACTIVE_POLICY.parameters,scenario.seed,count,Number.POSITIVE_INFINITY,evaluations.find(item=>item.constraints.feasible)?.candidate.id))}));
  const risks=rankRobustRisks(runs[0].value.map((item,index)=>evaluateRobustRisk(evaluations[index],item,DEFAULT_ACTIVE_POLICY.parameters)));
  const boundary=measured(()=>analyzeDecisionBoundary(state,taiwanMarket,scenario.seed,risks[0].candidateId,DEFAULT_ACTIVE_POLICY.parameters,evaluations,risks));
  const original=evaluateScenario(scenario,taiwanMarket,{samples:24,v3:{trajectoryCount:64}});
  const replay=measured(()=>replayDecisionV3(original.v3.audit,taiwanMarket));
  const report={worldModelFusionMs:fusion.ms,trajectory100Ms:runs[0].ms,trajectory500Ms:runs[1].ms,trajectory1000Ms:runs[2].ms,counterfactualBoundaryMs:boundary.ms,replayMs:replay.ms};
  console.log(`ARCI_V3_BENCHMARK ${JSON.stringify(report)}`);
  expect(runs.map(item=>item.value[0].forecast.trajectoryCount)).toEqual([100,500,1000]);
  expect(replay.value.matched).toBe(true);
  expect(report.worldModelFusionMs).toBeLessThan(200);
  expect(report.trajectory1000Ms).toBeLessThan(10_000);
  expect(report.counterfactualBoundaryMs).toBeLessThan(2_000);
  expect(report.replayMs).toBeLessThan(5_000);
});
